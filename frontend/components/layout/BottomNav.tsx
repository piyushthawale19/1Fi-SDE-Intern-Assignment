export function BottomNav() {
  const router = useRouter();

  return (
    <nav className="bottom-nav">
      {navItems.map((item) => {
        const isActive = router.pathname === item.href || (item.href !== '/shop' && router.pathname.startsWith(item.href));
        return (
          <Link key={item.label} href={item.href} className={`bottom-nav-item ${isActive ? 'active' : ''}`}>
            {item.icon(isActive)}
            {item.label}
          </Link>
        );
      })}
    </nav>
  );
}
